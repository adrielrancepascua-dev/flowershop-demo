function atManilaHour(base: Date, dayOffset: number, hour: number, minute = 0): Date {
  const dateKey = toManilaDateKeyFromDate(
    new Date(base.getTime() + dayOffset * 24 * 60 * 60 * 1000),
  );
  // Store as a Manila wall-clock instant (UTC+8) so calendar/report grouping stays correct.
  return new Date(`${dateKey}T${String(hour).padStart(2, '0')}:${String(minute).padStart(2, '0')}:00+08:00`);
}

function iso(base: Date, dayOffset: number, hour: number, minute = 0): string {
  return atManilaHour(base, dayOffset, hour, minute).toISOString();
}

function dateKey(base: Date, dayOffset: number): string {
  return toManilaDateKeyFromDate(new Date(base.getTime() + dayOffset * 24 * 60 * 60 * 1000));
}

type OrderDraft = Omit<
  FlowerOrder,
  | 'balance'
  | 'balance_paid'
  | 'balance_payment_mode'
  | 'balance_payment_reference'
  | 'photo_inspo_data_url'
  | 'proof_dp_data_url'
  | 'order_form_ss_data_url'
  | 'ready_photo_data_url'
  | 'content_edited_at'
  | 'inventory_deducted'
> & {
  balance_paid?: boolean;
  balance_payment_mode?: FlowerOrder['balance_payment_mode'];
  balance_payment_reference?: string;
  photo_inspo_data_url?: string;
  proof_dp_data_url?: string;
  order_form_ss_data_url?: string;
  ready_photo_data_url?: string;
  content_edited_at?: string | null;
  inventory_deducted?: boolean;
};

function finalizeOrder(draft: OrderDraft): FlowerOrder {
  const balance = Math.max(0, draft.total_amount - draft.downpayment);
  const balancePaid = draft.balance_paid ?? balance === 0;
  return {
    ...draft,
    balance: balancePaid ? 0 : balance,
    balance_paid: balancePaid,
    balance_payment_mode: draft.balance_payment_mode ?? (balancePaid && balance > 0 ? draft.payment_mode : ''),
    balance_payment_reference: draft.balance_payment_reference ?? '',
    photo_inspo_data_url: draft.photo_inspo_data_url || '',
    proof_dp_data_url: draft.proof_dp_data_url || '',
    order_form_ss_data_url: draft.order_form_ss_data_url || '',
    ready_photo_data_url: draft.ready_photo_data_url || '',
    content_edited_at: draft.content_edited_at ?? null,
    inventory_deducted: draft.inventory_deducted ?? false,
  };
}

